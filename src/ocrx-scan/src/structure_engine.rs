/// Scripted verdicts in region order; an empty script answers further
/// regions with [`EngineErrorKind::EngineDown`].
#[derive(Debug, Clone, Default)]
pub struct FakeStructureEngine {
    pub verdicts: std::collections::VecDeque<Result<StructureOutcome, EngineErrorKind>>,
    pub calls: Vec<(Vec<u8>, u32, usize)>,
}

impl FakeStructureEngine {
    #[must_use]
    pub fn with_html(htmls: &[&str]) -> Self {
        Self {
            verdicts: htmls
                .iter()
                .map(|html| Ok(StructureOutcome::Html((*html).to_owned())))
                .collect(),
            calls: Vec::new(),
        }
    }

    #[must_use]
    pub fn with_verdicts(verdicts: Vec<Result<StructureOutcome, EngineErrorKind>>) -> Self {
        Self {
            verdicts: verdicts.into(),
            calls: Vec::new(),
        }
    }
}

impl StructureTableEngine for FakeStructureEngine {
    fn recognize(
        &mut self,
        png: &[u8],
        page: u32,
        ordinal: usize,
    ) -> Result<StructureOutcome, EngineErrorKind> {
        self.calls.push((png.to_vec(), page, ordinal));
        match self.verdicts.pop_front() {
            Some(verdict) => verdict,
            None => Err(EngineErrorKind::EngineDown),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn base64_encode_matches_known_vectors() {
        assert_eq!(base64_encode(b""), "");
        assert_eq!(base64_encode(b"f"), "Zg==");
        assert_eq!(base64_encode(b"fo"), "Zm8=");
        assert_eq!(base64_encode(b"foo"), "Zm9v");
        assert_eq!(base64_encode(b"foobar"), "Zm9vYmFy");
    }

    #[test]
    fn hello_identity_mismatch_lists_every_field() {
        let hello = EngineIdentity {
            engine: "other".to_owned(),
            revision: "deadbeef".to_owned(),
            paddleocr: "1.0".to_owned(),
            paddlex: "1.0".to_owned(),
            paddlepaddle: "1.0".to_owned(),
            models_sha256: BTreeMap::new(),
        };
        let mismatches = hello.mismatches_against_frozen();
        // 5 version fields + one entry per frozen model dir (empty models
        // map = every frozen model missing).
        assert_eq!(
            mismatches.len(),
            5 + 8,
            "every frozen field must be compared"
        );
    }

    #[test]
    fn hello_identity_exact_match_has_no_mismatch() {
        // The hello must report EVERY frozen model dir with the exact frozen
        // hash (the real manifest is embedded via include_str!).
        let manifest: serde_json::Value = serde_json::from_str(FROZEN_MODELS_MANIFEST).unwrap();
        let models = manifest
            .get("models")
            .and_then(serde_json::Value::as_object)
            .unwrap();
        let hello: EngineIdentity = serde_json::from_str(
            r#"{"type":"hello","engine":"slanet-plus","revision":"bae6e5f8","paddleocr":"3.7.0",
                "paddlex":"3.7.2","paddlepaddle":"3.4.0"}"#,
        )
        .unwrap();
        assert!(
            !hello.mismatches_against_frozen().is_empty(),
            "empty models_sha256 must fail the frozen-model check"
        );
        let mut full = hello.clone();
        for (name, entry) in models {
            full.models_sha256.insert(
                name.clone(),
                ModelHash {
                    files: entry
                        .get("files")
                        .and_then(serde_json::Value::as_u64)
                        .unwrap_or(0),
                    sha256: entry
                        .get("sha256")
                        .and_then(serde_json::Value::as_str)
                        .unwrap_or_default()
                        .to_owned(),
                },
            );
        }
        assert!(full.mismatches_against_frozen().is_empty());
        // Drift: one model hash wrong -> mismatch names it.
        let mut drifted = full.clone();
        if let Some(hash) = drifted.models_sha256.get_mut("SLANeXt_wired") {
            hash.sha256 = "drifted".to_owned();
        }
        let mismatches = drifted.mismatches_against_frozen();
        assert!(
            mismatches.iter().any(|m| m.contains("SLANeXt_wired")),
            "{mismatches:?}"
        );
    }

    #[test]
    fn fake_engine_scripts_verdicts_then_engine_down() {
        let mut engine = FakeStructureEngine::with_verdicts(vec![
            Ok(StructureOutcome::Html("<table>".to_owned())),
            Ok(StructureOutcome::Reject(StructureReject::NoRulingLines)),
            Err(EngineErrorKind::EngineError("boom".to_owned())),
        ]);
        assert_eq!(
            engine.recognize(b"a", 1, 0).unwrap(),
            StructureOutcome::Html("<table>".to_owned())
        );
        assert_eq!(
            engine.recognize(b"b", 1, 1).unwrap(),
            StructureOutcome::Reject(StructureReject::NoRulingLines)
        );
        assert_eq!(
            engine.recognize(b"c", 1, 2).unwrap_err(),
            EngineErrorKind::EngineError("boom".to_owned())
        );
        assert_eq!(
            engine.recognize(b"d", 1, 3).unwrap_err(),
            EngineErrorKind::EngineDown,
            "script exhausted -> engine_down (D-63 (4) shape)"
        );
        assert_eq!(engine.calls.len(), 4);
    }

    #[test]
    fn reject_reason_vocabulary_is_frozen() {
        assert_eq!(
            EngineErrorKind::EngineError("x".to_owned()).reject_reason(),
            "engine_error"
        );
        assert_eq!(EngineErrorKind::EngineDown.reject_reason(), "engine_down");
    }

    #[test]
    fn spawn_from_env_missing_is_startup_class() {
        // Missing lookup = startup-class error naming the env var (D-63 (2));
        // exercised via the lookup factor-out (no process-env mutation).
        let error = StructureEngineClient::spawn_from_lookup(None).unwrap_err();
        assert!(
            error.contains(ENGINE_CMD_ENV),
            "error must name the env var"
        );
    }
}
