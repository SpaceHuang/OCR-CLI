//! M4.2 T2: the SLANet-plus table-structure sidecar client (plan D-59/D-63).
//!
//! One long-lived `python worker.py` child per scan invocation, spawned at
//! scan start when `--table-structure-reread on` (BEFORE any page product —
//! D-63 (2): every startup-class failure is a hard error with no products).
//! Wire contract: `sidecar/table-engine/PROTOCOL.md` (frozen fixtures, both
//! sides test against them).
//!
//! Failure dispositions (D-63 table, frozen):
//! - startup (spawn/handshake/timeout) → hard error, caller exits nonzero;
//! - per-request fault (`error` frame / timeout) → [`EngineErrorKind::EngineError`]
//!   for THAT region (orchestration keeps the original, scan continues);
//! - process death / EOF → [`EngineErrorKind::EngineDown`] for every further
//!   region (no auto-restart in phase 1), scan completes normally.

use std::collections::BTreeMap;
use std::io::{BufRead, BufReader, Write};
use std::process::{Child, ChildStdin, Command, Stdio};
use std::time::Duration;

/// Frozen supply-chain identity (sidecar/table-engine/requirements.txt must
/// match; the handshake compares every field, D-63).
pub const EXPECTED_ENGINE: &str = "slanet-plus";
pub const EXPECTED_REVISION: &str = "bae6e5f8";
pub const EXPECTED_PADDLEOCR: &str = "3.7.0";
pub const EXPECTED_PADDLEX: &str = "3.7.2";
pub const EXPECTED_PADDLEPADDLE: &str = "3.4.0";

/// Handshake deadline (D-63 (2); the hello precedes any model load, so 30s
/// only covers interpreter boot + model-dir hashing).
pub const HANDSHAKE_TIMEOUT: Duration = Duration::from_secs(30);
/// Per-recognize deadline (D-63 (3); CPU measured 186.3s/table + margin).
pub const REQUEST_TIMEOUT: Duration = Duration::from_secs(600);

/// Environment variable carrying the full worker command (phase 1:
/// documented opt-in; missing env + flag ON = startup-class hard error).
pub const ENGINE_CMD_ENV: &str = "OCRX_TABLE_ENGINE_CMD";

/// Frozen model-dir audit hashes (D-63 supply-chain freeze; generated by
/// `m42_freeze_manifest.py` from the paddlex official_models cache).
const FROZEN_MODELS_MANIFEST: &str =
    include_str!("../../../assets/manifests/table-engine-slanet-plus/bae6e5f8/manifest.json");

/// The worker's hello identity (PROTOCOL.md handshake frame).
#[derive(Debug, Clone, PartialEq, Eq, serde::Deserialize, serde::Serialize)]
pub struct EngineIdentity {
    pub engine: String,
    pub revision: String,
    pub paddleocr: String,
    pub paddlex: String,
    pub paddlepaddle: String,
    #[serde(default)]
    pub models_sha256: BTreeMap<String, ModelHash>,
}

/// Per-model-dir audit hash (files count + content digest).
#[derive(Debug, Clone, PartialEq, Eq, serde::Deserialize, serde::Serialize)]
pub struct ModelHash {
    pub files: u64,
    pub sha256: String,
}

/// Structured per-region rejects (worker verdicts, not errors).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum StructureReject {
    /// Ruling-line pre-check gate failed (D-62; no pipeline run).
    NoRulingLines,
    /// Pipeline ran but produced no `pred_html`.
    EmptyOutput,
}

/// A successful region verdict.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum StructureOutcome {
    Html(String),
    Reject(StructureReject),
}

/// Runtime error classes (D-63 (3)/(4) mapping).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum EngineErrorKind {
    /// This region failed (timeout / `error` frame / decode problem) —
    /// keep the original, the worker stays usable.
    EngineError(String),
    /// The worker is dead (EOF / spawn failure after startup) — every
    /// further region fails without retry.
    EngineDown,
}

impl EngineErrorKind {
    /// The `f6_detail` reject-reason string (frozen vocabulary).
    #[must_use]
    pub fn reject_reason(&self) -> &'static str {
        match self {
            EngineErrorKind::EngineError(_) => "engine_error",
            EngineErrorKind::EngineDown => "engine_down",
        }
    }
}

impl std::fmt::Display for EngineErrorKind {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            EngineErrorKind::EngineError(message) => write!(f, "engine_error: {message}"),
            EngineErrorKind::EngineDown => write!(f, "engine_down"),
        }
    }
}

/// F6 decode port: one cropped table region in, a verdict out. The fake
/// drives every orchestration test; the client implements it in production.
pub trait StructureTableEngine {
    fn recognize(
        &mut self,
        png: &[u8],
        page: u32,
        ordinal: usize,
    ) -> Result<StructureOutcome, EngineErrorKind>;
}

/// The production sidecar client.
pub struct StructureEngineClient {
    child: Child,
    stdin: Option<ChildStdin>,
    /// `None` once a read timed out (the reader thread owns it) — the client
    /// is dead by construction then.
    reader: Option<BufReader<std::process::ChildStdout>>,
    identity: EngineIdentity,
    next_id: u64,
    dead: bool,
}

impl std::fmt::Debug for StructureEngineClient {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("StructureEngineClient")
            .field("identity", &self.identity)
            .field("next_id", &self.next_id)
            .field("dead", &self.dead)
            .finish_non_exhaustive()
    }
}

impl StructureEngineClient {
    /// Spawns the worker from [`ENGINE_CMD_ENV`] and completes the handshake.
    ///
    /// # Errors
    /// Startup-class failure (missing env / spawn failure / hello timeout /
    /// identity mismatch) — the caller must hard-error before any page
    /// product (D-63 (2)).
    pub fn spawn_from_env() -> Result<Self, String> {
        Self::spawn_from_lookup(std::env::var(ENGINE_CMD_ENV).ok())
    }

    /// The lookup is factored out so tests exercise the missing-env branch
    /// without mutating process state (the crate forbids `unsafe_code`).
    fn spawn_from_lookup(command: Option<String>) -> Result<Self, String> {
        let command = command.ok_or_else(|| {
            format!(
                "table-structure-reread on requires the {ENGINE_CMD_ENV} env var (full worker command, e.g. `python -X utf8 -u <sidecar>/worker.py`)"
            )
        })?;
        Self::spawn(&command)
    }

    /// Spawns the worker from an explicit command string.
    ///
    /// # Errors
    /// See [`Self::spawn_from_env`].
    pub fn spawn(command: &str) -> Result<Self, String> {
        let mut child = Command::new(if cfg!(windows) { "cmd" } else { "sh" })
            .arg(if cfg!(windows) { "/C" } else { "-c" })
            .arg(command)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .spawn()
            .map_err(|error| format!("table engine spawn failed: {error}"))?;
        let stdin = child.stdin.take().ok_or("table engine stdin missing")?;
        let stdout = child.stdout.take().ok_or("table engine stdout missing")?;
        let mut client = Self {
            child,
            stdin: Some(stdin),
            reader: Some(BufReader::new(stdout)),
            identity: EngineIdentity {
                engine: String::new(),
                revision: String::new(),
                paddleocr: String::new(),
                paddlex: String::new(),
                paddlepaddle: String::new(),
                models_sha256: BTreeMap::new(),
            },
            next_id: 0,
            dead: false,
        };
        if let Err(error) = client.handshake() {
            client.kill_child();
            return Err(error);
        }
        Ok(client)
    }

    fn handshake(&mut self) -> Result<(), String> {
        let line = self.read_line_deadline(HANDSHAKE_TIMEOUT)?;
        let value: serde_json::Value =
            serde_json::from_str(&line).map_err(|error| format!("hello malformed: {error}"))?;
        if value.get("type").and_then(serde_json::Value::as_str) != Some("hello") {
            return Err(format!("first frame was not hello: {line:.80}"));
        }
        let hello: EngineIdentity = serde_json::from_value(value)
            .map_err(|error| format!("hello fields malformed: {error}"))?;
        let mismatches = hello.mismatches_against_frozen();
        if !mismatches.is_empty() {
            return Err(format!(
                "table engine identity mismatch (fail-closed, D-63): {}",
                mismatches.join("; ")
            ));
        }
        self.identity = hello;
        Ok(())
    }

    /// One line with a wall-clock deadline. On timeout the reader is gone
    /// (thread-owned) and the client is dead by construction.
    fn read_line_deadline(&mut self, deadline: Duration) -> Result<String, String> {
        if self.dead {
            return Err("engine dead".to_owned());
        }
        let mut reader = self
            .reader
            .take()
            .ok_or_else(|| "engine reader already lost".to_owned())?;
        let (tx, rx) = std::sync::mpsc::channel();
        std::thread::spawn(move || {
            let mut line = String::new();
            let result = match reader.read_line(&mut line) {
                Ok(0) => Err("table engine exited (EOF)".to_owned()),
                Ok(_) => Ok(line),
                Err(error) => Err(format!("table engine read failed: {error}")),
            };
            let _ = tx.send((result, reader));
        });
        match rx.recv_timeout(deadline) {
            Ok((Ok(line), reader)) => {
                self.reader = Some(reader);
                Ok(line)
            }
            Ok((Err(message), reader)) => {
                self.reader = Some(reader);
                self.dead = true;
                Err(message)
            }
            Err(_) => {
                // The thread still owns the reader; the Drop kills the child
                // so the thread's blocking read terminates and unwinds.
                self.dead = true;
                Err(format!("timeout after {}s", deadline.as_secs()))
            }
        }
    }

    fn kill_child(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }

    /// The verified hello identity (audit; stored into `OcrIdentity`).
    #[must_use]
    pub fn identity(&self) -> &EngineIdentity {
        &self.identity
    }

    /// True once the worker is known-dead (D-63 (4): no auto-restart).
    #[must_use]
    pub fn is_dead(&self) -> bool {
        self.dead
    }

    fn send(&mut self, frame: String) -> Result<(), EngineErrorKind> {
        if self.dead {
            return Err(EngineErrorKind::EngineDown);
        }
        let result = if let Some(stdin) = self.stdin.as_mut() {
            stdin
                .write_all(frame.as_bytes())
                .and_then(|_| stdin.write_all(b"\n"))
                .and_then(|_| stdin.flush())
        } else {
            Err(std::io::Error::other("stdin closed"))
        };
        if result.is_err() {
            self.dead = true;
            return Err(EngineErrorKind::EngineDown);
        }
        Ok(())
    }
}

impl Drop for StructureEngineClient {
    fn drop(&mut self) {
        // Close stdin first (clean EOF shutdown), then ensure the child is
        // reaped either way.
        self.stdin = None;
        self.kill_child();
    }
}

impl StructureTableEngine for StructureEngineClient {
    fn recognize(
        &mut self,
        png: &[u8],
        page: u32,
        ordinal: usize,
    ) -> Result<StructureOutcome, EngineErrorKind> {
        if self.dead {
            return Err(EngineErrorKind::EngineDown);
        }
        let id = self.next_id;
        self.next_id += 1;
        let frame = format!(
            "{{\"type\":\"recognize\",\"id\":{id},\"png_b64\":\"{}\",\"page\":{page},\"ordinal\":{ordinal}}}",
            base64_encode(png),
        );
        self.send(frame)?;
        // Strictly serial protocol: the next frame must answer OUR id (the
        // worker never emits anything else between request and response).
        let line = self
            .read_line_deadline(REQUEST_TIMEOUT)
            .map_err(EngineErrorKind::EngineError)?;
        let parsed: serde_json::Value = serde_json::from_str(&line)
            .map_err(|error| EngineErrorKind::EngineError(format!("malformed frame: {error}")))?;
        let frame_id = parsed.get("id").and_then(serde_json::Value::as_u64);
        match (
            parsed.get("type").and_then(serde_json::Value::as_str),
            frame_id,
        ) {
            (Some("result"), Some(matched)) if matched == id => parse_result(&parsed),
            (Some("error"), Some(matched)) if matched == id => {
                let message = parsed
                    .get("message")
                    .and_then(serde_json::Value::as_str)
                    .unwrap_or("unspecified");
                Err(EngineErrorKind::EngineError(message.to_owned()))
            }
            _ => {
                self.dead = true;
                Err(EngineErrorKind::EngineError(format!(
                    "unexpected frame for id {id}: {line:.120}"
                )))
            }
        }
    }
}

fn parse_result(parsed: &serde_json::Value) -> Result<StructureOutcome, EngineErrorKind> {
    match parsed.get("ok").and_then(serde_json::Value::as_bool) {
        Some(true) => {
            let html = parsed
                .get("html")
                .and_then(serde_json::Value::as_str)
                .unwrap_or_default();
            Ok(StructureOutcome::Html(html.to_owned()))
        }
        Some(false) => {
            let reject = parsed
                .get("reject")
                .and_then(serde_json::Value::as_str)
                .unwrap_or_default();
            match reject {
                "no_ruling_lines" => Ok(StructureOutcome::Reject(StructureReject::NoRulingLines)),
                "empty_output" => Ok(StructureOutcome::Reject(StructureReject::EmptyOutput)),
                other => Err(EngineErrorKind::EngineError(format!(
                    "unknown reject reason: {other}"
                ))),
            }
        }
        None => Err(EngineErrorKind::EngineError(
            "result frame missing ok".to_owned(),
        )),
    }
}

/// Standard base64 (RFC 4648) — small local encoder, no new dependency.
fn base64_encode(data: &[u8]) -> String {
    const TABLE: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let b0 = chunk[0] as u32;
        let b1 = u32::from(*chunk.get(1).unwrap_or(&0));
        let b2 = u32::from(*chunk.get(2).unwrap_or(&0));
        let triple = (b0 << 16) | (b1 << 8) | b2;
        out.push(TABLE[(triple >> 18) as usize & 63] as char);
        out.push(TABLE[(triple >> 12) as usize & 63] as char);
        out.push(if chunk.len() > 1 {
            TABLE[(triple >> 6) as usize & 63] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            TABLE[triple as usize & 63] as char
        } else {
            '='
        });
    }
    out
}

impl EngineIdentity {
    fn mismatches_against_frozen(&self) -> Vec<String> {
        let mut out = Vec::new();
        if self.engine != EXPECTED_ENGINE {
            out.push(format!("engine {} != {EXPECTED_ENGINE}", self.engine));
        }
        if self.revision != EXPECTED_REVISION {
            out.push(format!("revision {} != {EXPECTED_REVISION}", self.revision));
        }
        if self.paddleocr != EXPECTED_PADDLEOCR {
            out.push(format!(
                "paddleocr {} != {EXPECTED_PADDLEOCR}",
                self.paddleocr
            ));
        }
        if self.paddlex != EXPECTED_PADDLEX {
            out.push(format!("paddlex {} != {EXPECTED_PADDLEX}", self.paddlex));
        }
        if self.paddlepaddle != EXPECTED_PADDLEPADDLE {
            out.push(format!(
                "paddlepaddle {} != {EXPECTED_PADDLEPADDLE}",
                self.paddlepaddle
            ));
        }
        // D-63: every frozen model dir must be reported with the exact
        // frozen hash (missing dir / drifted file = startup-class error).
        if let Ok(manifest) = serde_json::from_str::<serde_json::Value>(FROZEN_MODELS_MANIFEST) {
            let frozen = manifest
                .get("models")
                .and_then(serde_json::Value::as_object)
                .expect("frozen manifest has a models object");
            for (name, entry) in frozen {
                let sha = entry.get("sha256").and_then(serde_json::Value::as_str);
                match self.models_sha256.get(name) {
                    None => out.push(format!("model {name} missing from hello")),
                    Some(hash) if hash.sha256 != sha.unwrap_or_default() => {
                        out.push(format!("model {name} hash drift"));
                    }
                    _ => {}
                }
            }
        }
        out
    }
}

